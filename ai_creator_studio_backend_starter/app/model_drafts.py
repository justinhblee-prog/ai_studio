"""R-047: brand-model creation contract (MOCK ONLY): design values + instruction -> 6 ranked candidates -> choose one -> brand model.

Input ``v`` = the designer's picks (body type, skin tone, hair, face, expression, accessories, background, camera, light ...): a flat mapping of
short keys to a short text or a short list, validated by SHAPE (the exact catalogue is the design window's and may grow). The mock provider draws
6 clearly artificial placeholder pictures and ranks them by a deterministic "fit" score; nothing is generated by AI and nothing leaves the server.
A real provider is NOT connected: ``PROVIDER_MODE`` other than mock fails closed (NEED_USER: keys, cost cap, notice).

Choosing a candidate creates the brand model = a Character (identity from ``v``, the candidate as its first picture, up to 30 reference
pictures from the workspace for consistency) and files the candidate under "my library" kind ``model``. Candidates that were not chosen are
removed with the draft. Consistency from 15-30 reference pictures is only STORED here (ids on the character); whether and how a provider can use
them is an open question (see the R-047 report).
"""
from __future__ import annotations

import hashlib
import io
import json
import re
import uuid
from datetime import datetime, timezone
from typing import Any

from fastapi import APIRouter, Depends, HTTPException
from PIL import Image, ImageDraw
from pydantic import BaseModel, ConfigDict, Field

from app import config, takedown
from app.assets import store
from app.assets.routes import current_user, require_role
from app.assets.validation import validate_image_upload

router = APIRouter(prefix="/v1/workspaces/{workspace_id}/model-drafts", tags=["model-drafts"])
CANDIDATES = 6
MAX_KEYS, MAX_VALUE, MAX_LIST = 40, 60, 10
KEY_RE = re.compile(r"^[a-z][a-z0-9_]{0,30}$")
MAX_OPEN_DRAFTS = 20
MAX_REFERENCES, RECOMMENDED_MIN_REFERENCES = 30, 15
EVENT = "asset.model_candidate"
# design keys that map straight onto the Character identity; everything else is kept whole under identity["design"]
IDENTITY_KEYS = {"gender": "gender", "gen": "gender", "age_range": "age_range", "age": "age_range", "face_shape": "face_shape", "face": "face_shape",
                 "eye_shape": "eye_shape", "eyes": "eye_shape", "nose_shape": "nose_shape", "nose": "nose_shape", "lip_shape": "lip_shape", "lips": "lip_shape",
                 "hairstyle": "hairstyle", "hs": "hairstyle", "hair_color": "hair_color", "hair": "hair_color", "body_type": "body_type", "body": "body_type",
                 "skin_tone": "skin_tone", "skin": "skin_tone", "skin_texture": "skin_texture"}
# The first spelling of a field that is present wins; the homepage studio's own keys (skin, body, gen, age, face, eyes, nose, lips, hair = hair COLOUR,
# hs = hair STYLE) are accepted next to the long names. Values may be a short text or a small whole number (the studio sends swatch / style indexes).
MAX_INT = 9999


def _init(db) -> None:
    db.execute("""CREATE TABLE IF NOT EXISTS model_drafts (
        draft_id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, owner_id TEXT NOT NULL, design_json TEXT NOT NULL, instruction TEXT,
        provider TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('ready','selected')), selected_index INTEGER, character_id TEXT,
        created_at TEXT NOT NULL, selected_at TEXT)""")
    db.execute("""CREATE TABLE IF NOT EXISTS model_draft_candidates (
        draft_id TEXT NOT NULL REFERENCES model_drafts(draft_id) ON DELETE CASCADE, workspace_id TEXT NOT NULL, rank INTEGER NOT NULL,
        asset_id TEXT NOT NULL, score INTEGER NOT NULL, PRIMARY KEY(draft_id, rank))""")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


Design = dict[str, "str | list[str]"]


def validate_design(v: Any) -> dict[str, Any]:
    """Shape check only: flat, short, text. Unknown keys are allowed (the catalogue belongs to the design window) but never nested or huge."""
    if not isinstance(v, dict) or not v:
        raise HTTPException(status_code=422, detail={"code": "DESIGN_REQUIRED", "message": "give at least one design value"})
    if len(v) > MAX_KEYS:
        raise HTTPException(status_code=422, detail={"code": "DESIGN_TOO_MANY", "message": f"at most {MAX_KEYS} design values"})
    out: dict[str, Any] = {}
    for key, value in v.items():
        if not isinstance(key, str) or not KEY_RE.match(key):
            raise HTTPException(status_code=422, detail={"code": "DESIGN_KEY_INVALID", "message": "keys are lowercase letters, digits and underscores"})
        items = value if isinstance(value, list) else [value]
        if not items or len(items) > MAX_LIST or any(not _scalar_ok(i) for i in items):
            raise HTTPException(status_code=422, detail={"code": "DESIGN_VALUE_INVALID",
                                                         "message": f"{key}: give a short text or a whole number 0-{MAX_INT}, or a short list of them"})
        out[key] = [_norm(i) for i in value] if isinstance(value, list) else _norm(value)
    return out


def _scalar_ok(item: Any) -> bool:
    if isinstance(item, bool):
        return False
    if isinstance(item, int):
        return 0 <= item <= MAX_INT
    return isinstance(item, str) and bool(item.strip()) and len(item) <= MAX_VALUE


def _norm(item: Any) -> Any:
    return item.strip() if isinstance(item, str) else item


class DraftIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    v: dict[str, Any]
    prompt: str | None = Field(default=None, max_length=500)


class SelectIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    rank: int = Field(ge=1, le=CANDIDATES)
    name: str = Field(min_length=1, max_length=120)
    reference_asset_ids: list[str] = Field(default_factory=list, max_length=MAX_REFERENCES)


_LIKENESS = re.compile(
    r"(닮|똑같|흉내|복제|비슷하게\s*생|처럼\s*생|연예인|유명인|셀럽|아이돌|정치인|대통령|실존\s*인물|실제\s*인물|딥페이크"
    r"|look(?:s|ing)?[\s-]*like|lookalike|resembl|celebrit|real[\s-]*person|real[\s-]*people|likeness\s+of|deep[\s-]*fake|clone\s+of|modeled\s+(?:on|after))",
    re.IGNORECASE)


def likeness_requested(text: str) -> bool:
    """True when the wording asks for a real person's likeness (rule-based, deliberately cautious: it can over-block an innocent sentence; the person is told to rephrase)."""
    return bool(text and _LIKENESS.search(text))


def _digest(design: dict[str, Any], prompt: str | None, salt: str) -> bytes:
    return hashlib.sha256((json.dumps(design, sort_keys=True, ensure_ascii=False) + "|" + (prompt or "") + "|" + salt).encode()).digest()


def mock_candidate(design: dict[str, Any], prompt: str | None, n: int) -> tuple[bytes, int]:
    """A deterministic artificial placeholder (a flat figure on a plain backdrop) and its 'fit' score 60..99. Same input -> same output."""
    d = _digest(design, prompt, str(n))
    bg, body = (200 + d[0] % 40, 200 + d[1] % 40, 200 + d[2] % 40), (40 + d[3] % 160, 40 + d[4] % 160, 40 + d[5] % 160)
    img = Image.new("RGB", (256, 384), bg)
    draw = ImageDraw.Draw(img)
    draw.ellipse((98, 40, 158, 110), fill=(224, 190 - d[6] % 40, 160 - d[7] % 40))
    draw.rounded_rectangle((78, 118, 178, 330), radius=24, fill=body)
    draw.text((8, 366), f"MOCK #{n} - not AI", fill=(90, 90, 90))
    buf = io.BytesIO(); img.save(buf, format="PNG")
    return buf.getvalue(), 60 + d[8] % 40


def _public(db, draft) -> dict[str, Any]:
    cands = db.execute("SELECT rank, asset_id, score FROM model_draft_candidates WHERE draft_id=? ORDER BY rank", (draft["draft_id"],)).fetchall()
    return {"draft_id": draft["draft_id"], "workspace_id": draft["workspace_id"], "owner_id": draft["owner_id"], "v": json.loads(draft["design_json"]),
            "prompt": draft["instruction"], "provider": draft["provider"], "status": draft["status"], "selected_rank": draft["selected_index"],
            "character_id": draft["character_id"], "created_at": draft["created_at"], "selected_at": draft["selected_at"],
            "candidates": [{"rank": c["rank"], "asset_id": c["asset_id"], "score": c["score"]} for c in cands]}


class CandidateOut(BaseModel):
    rank: int
    asset_id: str
    score: int


class DraftOut(BaseModel):
    draft_id: str
    workspace_id: str
    owner_id: str
    v: dict[str, Any]
    prompt: str | None
    provider: str
    status: str
    selected_rank: int | None
    character_id: str | None
    created_at: str
    selected_at: str | None
    candidates: list[CandidateOut]


class DraftListOut(BaseModel):
    items: list[DraftOut]


class SelectOut(BaseModel):
    draft: DraftOut
    character_id: str
    library_item_id: str | None
    references: int
    consistency_ready: bool
    recommended_min_references: int
    max_references: int


@router.post("", status_code=201, response_model=DraftOut, operation_id="createModelDraft")
async def create_draft(workspace_id: str, body: DraftIn, user_id: str = Depends(current_user)):
    require_role(workspace_id, user_id, {"owner", "admin", "editor"})
    from app import rate_limit    # R-067
    rate_limit.check("generate", user_id, workspace_id)
    if config.PROVIDER_MODE != "mock":
        raise HTTPException(status_code=409, detail={"code": "MODEL_PROVIDER_NOT_CONNECTED",
                            "message": "Model generation by an external AI service is not connected yet."})
    design = validate_design(body.v)
    prompt = (body.prompt or "").strip() or None
    texts = [prompt or ""] + [str(x) for value in design.values() for x in (value if isinstance(value, list) else [value])]
    if any(likeness_requested(t) for t in texts):    # R-074: a brand model is invented, never made to look like a real person
        raise HTTPException(status_code=422, detail={"code": "MODEL_REAL_PERSON_BLOCKED", "message": "A brand model cannot be made to look like a real person."})
    with store._connect() as db:
        _init(db)
        open_n = db.execute("SELECT COUNT(*) AS n FROM model_drafts WHERE workspace_id=? AND status='ready'", (workspace_id,)).fetchone()["n"]
    if open_n >= MAX_OPEN_DRAFTS:
        raise HTTPException(status_code=409, detail={"code": "MODEL_DRAFT_LIMIT", "message": f"at most {MAX_OPEN_DRAFTS} open drafts; delete or choose from one first"})
    made = sorted((mock_candidate(design, prompt, n) + (n,) for n in range(1, CANDIDATES + 1)), key=lambda t: (-t[1], t[2]))
    draft_id = "mdr_" + uuid.uuid4().hex
    saved: list[tuple[int, str, int]] = []
    for rank, (content, score, n) in enumerate(made, start=1):
        filename = f"model-candidate-{draft_id[-6:]}-{rank}.png"
        validated = validate_image_upload(filename, content, max_bytes=config.ASSET_MAX_UPLOAD_BYTES)
        asset = store.save_asset(owner_id=user_id, workspace_id=workspace_id, filename=filename, content=content, validated=validated, provenance_event=EVENT,
                                 provenance_extra={"draft_id": draft_id, "rank": rank, "mode": "mock", "is_ai_generated": False})
        saved.append((rank, asset["asset_id"], score))
    with store._connect() as db:
        _init(db)
        db.execute("INSERT INTO model_drafts(draft_id, workspace_id, owner_id, design_json, instruction, provider, status, created_at) VALUES (?,?,?,?,?,?,?,?)",
                   (draft_id, workspace_id, user_id, json.dumps(design, ensure_ascii=False), prompt, "mock", "ready", _now()))
        db.executemany("INSERT INTO model_draft_candidates(draft_id, workspace_id, rank, asset_id, score) VALUES (?,?,?,?,?)",
                       [(draft_id, workspace_id, r, a, s) for r, a, s in saved])
        return _public(db, db.execute("SELECT * FROM model_drafts WHERE draft_id=?", (draft_id,)).fetchone())


@router.get("", response_model=DraftListOut, operation_id="listModelDrafts")
async def list_drafts(workspace_id: str, user_id: str = Depends(current_user)):
    require_role(workspace_id, user_id, {"owner", "admin", "editor", "viewer"})
    with store._connect() as db:
        _init(db)
        rows = db.execute("SELECT * FROM model_drafts WHERE workspace_id=? ORDER BY created_at DESC, draft_id LIMIT 100", (workspace_id,)).fetchall()
        return {"items": [_public(db, r) for r in rows]}


def _load(db, workspace_id: str, draft_id: str):
    row = db.execute("SELECT * FROM model_drafts WHERE draft_id=? AND workspace_id=?", (draft_id, workspace_id)).fetchone()
    if row is None:
        raise HTTPException(status_code=404, detail="Model draft not found")
    return row


@router.get("/{draft_id}", response_model=DraftOut, operation_id="getModelDraft")
async def get_draft(workspace_id: str, draft_id: str, user_id: str = Depends(current_user)):
    require_role(workspace_id, user_id, {"owner", "admin", "editor", "viewer"})
    with store._connect() as db:
        _init(db)
        return _public(db, _load(db, workspace_id, draft_id))


def identity_from_design(name: str, design: dict[str, Any]) -> dict[str, Any]:
    identity: dict[str, Any] = {"name": name.strip()}
    for key, field in IDENTITY_KEYS.items():
        if key in design and field not in identity:
            value = design[key]
            identity[field] = (", ".join(str(x) for x in value) if isinstance(value, list) else str(value))[:100]
    identity["design"] = design   # the whole pick list, so nothing the designer chose is lost
    return identity


@router.post("/{draft_id}/select", response_model=SelectOut, operation_id="selectModelDraftCandidate")
async def select_candidate(workspace_id: str, draft_id: str, body: SelectIn, user_id: str = Depends(current_user)):
    require_role(workspace_id, user_id, {"owner", "admin", "editor"})
    if not body.name.strip():
        raise HTTPException(status_code=422, detail={"code": "MODEL_NAME_REQUIRED", "message": "the brand model needs a name"})
    if len(set(body.reference_asset_ids)) != len(body.reference_asset_ids):
        raise HTTPException(status_code=422, detail={"code": "REFERENCE_DUPLICATE", "message": "reference pictures must be distinct"})
    with store._connect() as db:
        _init(db)
        draft = _load(db, workspace_id, draft_id)
        if draft["status"] != "ready":
            raise HTTPException(status_code=409, detail={"code": "MODEL_DRAFT_ALREADY_CHOSEN", "message": "a candidate was already chosen from this draft"})
        cand = db.execute("SELECT * FROM model_draft_candidates WHERE draft_id=? AND rank=?", (draft_id, body.rank)).fetchone()
        design = json.loads(draft["design_json"])
    if cand is None:
        raise HTTPException(status_code=404, detail="Candidate not found")
    for asset_id in body.reference_asset_ids:
        asset = store.get_asset(asset_id, workspace_id)
        if asset is None or asset["asset_kind"] != "image" or not takedown.visible_to(asset_id, user_id) or asset_id == cand["asset_id"]:
            raise HTTPException(status_code=422, detail={"code": "REFERENCE_INVALID", "message": f"{asset_id} is not an image of this workspace"})
    from app.ports.characters import get_character_port
    from app.repo_errors import raise_http
    try:
        character = get_character_port().create(workspace_id, user_id, {"identity": identity_from_design(body.name, design), "outfits": [], "active_outfit_id": None},
                                                [cand["asset_id"], *body.reference_asset_ids])
    except Exception as exc:
        raise_http(exc)
    from app.workspace_library import file_item
    filed = file_item(workspace_id, cand["asset_id"], user_id, "model", body.name)
    with store._connect() as db:
        _init(db)
        db.execute("UPDATE model_drafts SET status='selected', selected_index=?, character_id=?, selected_at=? WHERE draft_id=? AND status='ready'",
                   (body.rank, character["character_id"], _now(), draft_id))
        out = _public(db, _load(db, workspace_id, draft_id))
        item = db.execute("SELECT item_id FROM workspace_library_items WHERE workspace_id=? AND asset_id=?", (workspace_id, cand["asset_id"])).fetchone()
    # the candidates that were not chosen are no longer needed
    _discard(workspace_id, [c["asset_id"] for c in out["candidates"] if c["asset_id"] != cand["asset_id"]], user_id)
    n = len(body.reference_asset_ids)
    return {"draft": out, "character_id": character["character_id"], "library_item_id": item["item_id"] if item else None, "references": n,
            "consistency_ready": n >= RECOMMENDED_MIN_REFERENCES, "recommended_min_references": RECOMMENDED_MIN_REFERENCES, "max_references": MAX_REFERENCES}


def _discard(workspace_id: str, asset_ids: list[str], user_id: str) -> None:
    for asset_id in asset_ids:
        try:
            store.delete_asset(asset_id, workspace_id, user_id)
        except Exception:  # noqa: BLE001 - a candidate that cannot be removed (for example still referenced) simply stays
            pass


@router.delete("/{draft_id}", status_code=204, operation_id="deleteModelDraft")
async def delete_draft(workspace_id: str, draft_id: str, user_id: str = Depends(current_user)):
    """Removes the draft and every candidate that was not chosen (the chosen picture belongs to the brand model and the library)."""
    require_role(workspace_id, user_id, {"owner", "admin", "editor"})
    with store._connect() as db:
        _init(db)
        draft = _load(db, workspace_id, draft_id)
        keep = None
        if draft["selected_index"] is not None:
            row = db.execute("SELECT asset_id FROM model_draft_candidates WHERE draft_id=? AND rank=?", (draft_id, draft["selected_index"])).fetchone()
            keep = row["asset_id"] if row else None
        assets = [r["asset_id"] for r in db.execute("SELECT asset_id FROM model_draft_candidates WHERE draft_id=?", (draft_id,)).fetchall()]
        db.execute("DELETE FROM model_draft_candidates WHERE draft_id=?", (draft_id,))
        db.execute("DELETE FROM model_drafts WHERE draft_id=?", (draft_id,))
    _discard(workspace_id, [a for a in assets if a != keep], user_id)
    return None

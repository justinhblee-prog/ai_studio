-- All application tables are RLS-enabled with no client policies yet (default deny).
-- Backend access is expected through a server-side service_role connection only.

CREATE TABLE IF NOT EXISTS generation_jobs (
    job_id TEXT PRIMARY KEY,
    workspace_id TEXT NOT NULL,
    owner_id TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('queued','running','post_processing','succeeded','failed','cancelled','canceled')),
    provider TEXT NOT NULL,
    model TEXT,
    provider_request_id TEXT,
    output_url TEXT,
    error_code TEXT,
    message TEXT,
    payload_hash TEXT NOT NULL,
    payload_json JSONB NOT NULL,
    provider_output_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_generation_jobs_workspace_created ON generation_jobs(workspace_id, created_at DESC);

CREATE TABLE IF NOT EXISTS generation_executions (
    execution_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    status TEXT NOT NULL,
    provider TEXT NOT NULL,
    provider_request_id TEXT,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    error_code TEXT,
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE(job_id, attempt_no)
);
CREATE INDEX IF NOT EXISTS idx_generation_executions_job_attempt ON generation_executions(job_id, attempt_no DESC);

CREATE TABLE IF NOT EXISTS generation_job_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    from_status TEXT,
    to_status TEXT NOT NULL,
    event_type TEXT NOT NULL,
    actor_id TEXT,
    payload_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_generation_events_job ON generation_job_events(job_id, event_id);

CREATE TABLE IF NOT EXISTS generation_outputs (
    output_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL UNIQUE REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    storage_key TEXT NOT NULL,
    media_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    checksum_sha256 TEXT
);

CREATE TABLE IF NOT EXISTS generation_output_asset_links (
    link_id TEXT PRIMARY KEY,
    output_id TEXT NOT NULL UNIQUE REFERENCES generation_outputs(output_id) ON DELETE CASCADE,
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    workspace_id TEXT NOT NULL,
    owner_id TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending','processing','linked','failed')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL,
    claimed_by TEXT,
    claimed_at TIMESTAMPTZ,
    lease_expires_at TIMESTAMPTZ,
    asset_id TEXT,
    asset_version_id TEXT,
    provenance_id TEXT,
    checksum_sha256 TEXT,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_output_asset_links_ready ON generation_output_asset_links(status, available_at, created_at);

CREATE TABLE IF NOT EXISTS generation_output_asset_link_events (
    event_id TEXT PRIMARY KEY,
    link_id TEXT NOT NULL REFERENCES generation_output_asset_links(link_id),
    output_id TEXT NOT NULL,
    job_id TEXT NOT NULL,
    actor_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    details_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_output_asset_link_events ON generation_output_asset_link_events(link_id, created_at, event_id);

CREATE TABLE IF NOT EXISTS generation_idempotency (
    workspace_id TEXT NOT NULL,
    idempotency_key TEXT NOT NULL,
    payload_hash TEXT NOT NULL,
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(workspace_id, idempotency_key)
);

CREATE TABLE IF NOT EXISTS generation_outbox (
    event_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    payload_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL CHECK (status IN ('pending','processing','processed','needs_reconciliation')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL,
    claimed_by TEXT,
    claimed_at TIMESTAMPTZ,
    lease_expires_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_generation_outbox_ready ON generation_outbox(status, available_at, created_at);

CREATE TABLE IF NOT EXISTS generation_worker_heartbeats (
    worker_id TEXT PRIMARY KEY,
    started_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    state TEXT NOT NULL,
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS generation_poll_tasks (
    task_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL UNIQUE REFERENCES generation_jobs(job_id) ON DELETE CASCADE,
    phase TEXT NOT NULL CHECK (phase IN ('status','persist_output')),
    status TEXT NOT NULL CHECK (status IN ('pending','processing','completed','needs_reconciliation')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL,
    claimed_by TEXT,
    claimed_at TIMESTAMPTZ,
    lease_expires_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_generation_poll_ready ON generation_poll_tasks(status, available_at, created_at);

CREATE TABLE IF NOT EXISTS generation_ops_alerts (
    alert_id TEXT PRIMARY KEY,
    fingerprint TEXT NOT NULL UNIQUE,
    alert_type TEXT NOT NULL,
    severity TEXT NOT NULL CHECK (severity IN ('warning','critical')),
    status TEXT NOT NULL CHECK (status IN ('active','resolved')),
    title TEXT NOT NULL,
    details_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_generation_ops_alerts_status ON generation_ops_alerts(status, severity, last_seen_at);

CREATE TABLE IF NOT EXISTS generation_ops_alert_deliveries (
    delivery_id TEXT PRIMARY KEY,
    alert_id TEXT NOT NULL REFERENCES generation_ops_alerts(alert_id) ON DELETE CASCADE,
    destination TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending','processing','delivered','failed')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL,
    claimed_at TIMESTAMPTZ,
    claimed_by TEXT,
    lease_expires_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    delivered_at TIMESTAMPTZ,
    UNIQUE(alert_id, destination)
);
CREATE INDEX IF NOT EXISTS idx_generation_alert_delivery_ready ON generation_ops_alert_deliveries(status, available_at);

CREATE TABLE IF NOT EXISTS generation_output_review_events (
    event_id TEXT PRIMARY KEY,
    output_id TEXT NOT NULL REFERENCES generation_outputs(output_id),
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id),
    workspace_id TEXT NOT NULL,
    actor_id TEXT NOT NULL,
    decision TEXT NOT NULL CHECK (decision IN ('approved','changes_requested','rejected')),
    comment TEXT NOT NULL DEFAULT '',
    asset_id TEXT NOT NULL,
    asset_version_id TEXT NOT NULL,
    provenance_id TEXT NOT NULL,
    checksum_sha256 TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_generation_output_reviews ON generation_output_review_events(job_id, output_id, created_at, event_id);

CREATE TABLE IF NOT EXISTS generation_output_export_events (
    event_id TEXT PRIMARY KEY,
    job_id TEXT NOT NULL REFERENCES generation_jobs(job_id),
    workspace_id TEXT NOT NULL,
    actor_id TEXT NOT NULL,
    manifest_sha256 TEXT NOT NULL,
    output_count INTEGER NOT NULL CHECK (output_count > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_generation_output_exports ON generation_output_export_events(job_id, created_at, event_id);

CREATE OR REPLACE FUNCTION acs_reject_append_only_mutation() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'append-only event records cannot be updated or deleted';
END;
$$;
DROP TRIGGER IF EXISTS trg_output_review_events_no_update ON generation_output_review_events;
CREATE TRIGGER trg_output_review_events_no_update BEFORE UPDATE OR DELETE ON generation_output_review_events
FOR EACH ROW EXECUTE FUNCTION acs_reject_append_only_mutation();
DROP TRIGGER IF EXISTS trg_output_export_events_no_update ON generation_output_export_events;
CREATE TRIGGER trg_output_export_events_no_update BEFORE UPDATE OR DELETE ON generation_output_export_events
FOR EACH ROW EXECUTE FUNCTION acs_reject_append_only_mutation();

